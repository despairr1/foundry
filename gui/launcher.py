"""The Launch button next to a project's name: finds how to start the project, or asks Claude to make a launcher.

A project Foundry built for the Launch button keeps `<project>/.foundry/launcher.json`:
    {"command": "python main.py", "cwd": ".", "icon": "assets/icon.ico", "name": "Weather"}
Without it, common conventions are recognized (launch.bat, package.json's start script, main.py, cargo, go...)."""
import json
import os
import sys

LAUNCHER_FILE = os.path.join(".foundry", "launcher.json")

SCRIPT_NAMES = ["launch", "run", "start"]
SCRIPT_EXTENSIONS = [".bat", ".cmd", ".ps1"] if sys.platform == "win32" else [".sh"]
PYTHON_ENTRIES = ["main.py", "app.py", "__main__.py", "run.py"]


def _script_command(name):
    if name.lower().endswith(".ps1"):
        return f"& .\\{name}" if sys.platform == "win32" else f"pwsh ./{name}"
    return f".\\{name}" if sys.platform == "win32" else f"./{name}"


def find_launcher(folder):
    """{"command", "cwd", "source", "icon", "name"} describing how to start the project, or None.
    source: "launcher.json", "script", "package.json", "python", "cargo", "go" or "html" (open in the browser)."""
    if not folder or not os.path.isdir(folder):
        return None
    saved = os.path.join(folder, LAUNCHER_FILE)
    if os.path.isfile(saved):
        try:
            with open(saved, "r", encoding="utf-8") as f:
                data = json.load(f)
            command = str(data.get("command", "")).strip()
            if command:
                cwd = os.path.normpath(os.path.join(folder, str(data.get("cwd") or ".")))
                icon = str(data.get("icon") or "").strip()
                return {"command": command, "cwd": cwd if os.path.isdir(cwd) else folder, "source": "launcher.json",
                        "icon": os.path.join(folder, icon) if icon else None, "name": str(data.get("name") or "").strip() or None}
        except Exception:
            pass
    for name in SCRIPT_NAMES:
        for ext in SCRIPT_EXTENSIONS:
            script = f"{name}{ext}"
            if os.path.isfile(os.path.join(folder, script)):
                return {"command": _script_command(script), "cwd": folder, "source": "script", "icon": None, "name": None}
    package = os.path.join(folder, "package.json")
    if os.path.isfile(package):
        try:
            with open(package, "r", encoding="utf-8") as f:
                scripts = json.load(f).get("scripts") or {}
            for script, command in (("start", "npm start"), ("dev", "npm run dev"), ("serve", "npm run serve")):
                if scripts.get(script):
                    return {"command": command, "cwd": folder, "source": "package.json", "icon": None, "name": None}
        except Exception:
            pass
    for entry in PYTHON_ENTRIES:
        if os.path.isfile(os.path.join(folder, entry)):
            return {"command": f"python {entry}", "cwd": folder, "source": "python", "icon": None, "name": None}
    if os.path.isfile(os.path.join(folder, "Cargo.toml")):
        return {"command": "cargo run", "cwd": folder, "source": "cargo", "icon": None, "name": None}
    if os.path.isfile(os.path.join(folder, "go.mod")):
        return {"command": "go run .", "cwd": folder, "source": "go", "icon": None, "name": None}
    if os.path.isfile(os.path.join(folder, "index.html")):
        return {"command": os.path.join(folder, "index.html"), "cwd": folder, "source": "html", "icon": None, "name": None}
    return None


def describe_launcher(launcher):
    source = launcher["source"]
    if source == "launcher.json":
        return f"Runs {launcher['command']} (from .foundry/launcher.json)"
    if source == "html":
        return "Opens index.html in your browser"
    return f"Runs {launcher['command']}"


def launcher_request(folder):
    """The message that asks Claude to make a launcher (and start the Build). Sent from the Make a launcher button."""
    system = "Windows" if sys.platform == "win32" else "macOS" if sys.platform == "darwin" else "Linux"
    script = "launch.bat" if sys.platform == "win32" else "launch.sh"
    return (
        f"Make a launcher for this project so it can be started with one click on {system}:\n"
        f"1. A {script} in the project folder that starts the program (installing what it needs first if that is quick).\n"
        f"2. An app icon: a simple logo for the project as assets/icon.png (and assets/icon.ico on Windows), generated by a script "
        f"in the project so it needs no image editor.\n"
        f"3. A desktop shortcut script (make-shortcut) that puts a shortcut with that icon on the desktop.\n"
        f"4. .foundry/launcher.json in the project folder, exactly like {{\"command\": \"<how to start it>\", \"cwd\": \".\", "
        f"\"icon\": \"assets/icon.ico\", \"name\": \"<app name>\"}}, which Foundry's Launch button reads.\n"
        f"Look at what is in the folder first, then go ahead and build it."
    )
